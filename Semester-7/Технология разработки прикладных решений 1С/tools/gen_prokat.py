def build(out):
    if os.path.isdir(out):
        shutil.rmtree(out)
    os.makedirs(out)

    # --- справочники ---
    catalog(out, 'МоделиВелосипедов', 'Модели велосипедов', 'Модель', 'Модели велосипедов',
            descr_len=100, attrs=[
                attribute('ЦенаЗаЧас', 'Цена за час', type_number(10, 2, nonneg=True), fill='ShowError'),
            ])
    catalog(out, 'Велосипеды', 'Велосипеды', 'Велосипед', 'Велосипеды', descr_len=100, attrs=[
        attribute('Модель', 'Модель', type_ref('Catalog', 'МоделиВелосипедов'), fill='ShowError'),
        attribute('Исправен', 'Исправен', BOOL),
    ])
    catalog(out, 'Клиенты', 'Клиенты', 'Клиент', 'Клиенты', descr_len=100, attrs=[
        attribute('Телефон', 'Телефон', type_string(20), fill='ShowError'),
        attribute('ПостоялецГостиницы', 'Постоялец гостиницы', BOOL),
        attribute('Гостиница', 'Гостиница', type_string(100)),
        attribute('НомерКомнаты', 'Номер комнаты', type_string(10)),
    ])

    # --- перечисления ---
    enumeration(out, 'ВидЗалога', 'Вид залога', [
        ('Деньги', 'Деньги'),
        ('ВодительскоеУдостоверение', 'Водительское удостоверение'),
        ('Паспорт', 'Паспорт'),
    ])
    enumeration(out, 'СостояниеВелосипеда', 'Состояние велосипеда', [
        ('Целый', 'Целый'),
        ('Испорчен', 'Испорчен'),
    ])

    # --- регистры ---
    accum_register(out, 'ВелосипедыВПрокате', 'Велосипеды в прокате',
        dims=[
            attribute('Велосипед', 'Велосипед', type_ref('Catalog', 'Велосипеды'), tag='Dimension'),
            attribute('Клиент', 'Клиент', type_ref('Catalog', 'Клиенты'), tag='Dimension'),
        ],
        ress=[attribute('Количество', 'Количество', type_number(5, 0), tag='Resource')])

    accum_register(out, 'Резервы', 'Резервы',
        dims=[attribute('Модель', 'Модель', type_ref('Catalog', 'МоделиВелосипедов'), tag='Dimension')],
        ress=[attribute('Количество', 'Количество', type_number(5, 0), tag='Resource')])

    accum_register(out, 'Выручка', 'Выручка',
        dims=[
            attribute('Модель', 'Модель', type_ref('Catalog', 'МоделиВелосипедов'), tag='Dimension'),
            attribute('Клиент', 'Клиент', type_ref('Catalog', 'Клиенты'), tag='Dimension'),
        ],
        ress=[
            attribute('Сумма', 'Сумма', type_number(15, 2), tag='Resource'),
            attribute('Часы', 'Часы', type_number(10, 0), tag='Resource'),
        ],
        reg_type='Turnovers')

    # --- документы ---
    document(out, 'Резервирование', 'Резервирование', attrs=[
        attribute('Клиент', 'Клиент', type_ref('Catalog', 'Клиенты'), fill='ShowError'),
        attribute('Модель', 'Модель', type_ref('Catalog', 'МоделиВелосипедов'), fill='ShowError'),
        attribute('Количество', 'Количество', type_number(5, 0, nonneg=True), fill='ShowError'),
        attribute('ДатаНачала', 'Дата начала', type_date('DateTime'), fill='ShowError'),
        attribute('ДатаОкончания', 'Дата окончания', type_date('DateTime')),
    ], registers=['AccumulationRegister.Резервы'], module=MOD_REZERV)

    vydacha_ts = tabular_section('Состав', 'Состав', owner='ВыдачаВелосипедов', attrs=[
        attribute('Велосипед', 'Велосипед', type_ref('Catalog', 'Велосипеды'), fill='ShowError', indent=5),
        attribute('ВремяВыдачи', 'Время выдачи', type_date('DateTime'), fill='ShowError', indent=5),
    ])
    document(out, 'ВыдачаВелосипедов', 'Выдача велосипедов', attrs=[
        attribute('Клиент', 'Клиент', type_ref('Catalog', 'Клиенты'), fill='ShowError'),
        attribute('ВидЗалога', 'Вид залога', '<v8:Type>cfg:EnumRef.ВидЗалога</v8:Type>', fill='ShowError'),
        attribute('СуммаЗалога', 'Сумма залога', type_number(10, 2, nonneg=True)),
        attribute('Резерв', 'Резерв', type_ref('Document', 'Резервирование')),
    ], tabsecs=[vydacha_ts],
       registers=['AccumulationRegister.ВелосипедыВПрокате', 'AccumulationRegister.Резервы'],
       module=MOD_VYDACHA)

    vozvrat_ts = tabular_section('Состав', 'Состав', owner='ВозвратВелосипедов', attrs=[
        attribute('Велосипед', 'Велосипед', type_ref('Catalog', 'Велосипеды'), fill='ShowError', indent=5),
        attribute('ВремяВыдачи', 'Время выдачи', type_date('DateTime'), indent=5),
        attribute('ВремяВозврата', 'Время возврата', type_date('DateTime'), fill='ShowError', indent=5),
        attribute('Состояние', 'Состояние', '<v8:Type>cfg:EnumRef.СостояниеВелосипеда</v8:Type>',
                  fill='ShowError', indent=5),
        attribute('Часы', 'Часы', type_number(10, 0), indent=5),
        attribute('Сумма', 'Сумма', type_number(15, 2), indent=5),
    ])
    document(out, 'ВозвратВелосипедов', 'Возврат велосипедов', attrs=[
        attribute('Клиент', 'Клиент', type_ref('Catalog', 'Клиенты'), fill='ShowError'),
        attribute('Выдача', 'Выдача', type_ref('Document', 'ВыдачаВелосипедов'), fill='ShowError'),
    ], tabsecs=[vozvrat_ts],
       registers=['AccumulationRegister.ВелосипедыВПрокате', 'AccumulationRegister.Выручка'],
       module=MOD_VOZVRAT, based_on=['Document.ВыдачаВелосипедов'])

    build_reports(out)

    subsystem(out, 'Справочники', 'Справочники',
              ['Catalog.МоделиВелосипедов', 'Catalog.Велосипеды', 'Catalog.Клиенты'])
    subsystem(out, 'Прокат', 'Прокат',
              ['Document.Резервирование', 'Document.ВыдачаВелосипедов', 'Document.ВозвратВелосипедов',
               'AccumulationRegister.ВелосипедыВПрокате', 'AccumulationRegister.Резервы',
               'AccumulationRegister.Выручка'])
    subsystem(out, 'Аналитика', 'Аналитика',
              ['Report.ВыручкаЗаПериод', 'Report.ВелосипедыВПрокате', 'Report.АналитикаПоКлиентам'])

    configuration(out, 'ПрокатВелосипедов', 'Прокат велосипедов', [
        '<Subsystem>Справочники</Subsystem>',
        '<Subsystem>Прокат</Subsystem>',
        '<Subsystem>Аналитика</Subsystem>',
        '<Catalog>МоделиВелосипедов</Catalog>',
        '<Catalog>Велосипеды</Catalog>',
        '<Catalog>Клиенты</Catalog>',
        '<Enum>ВидЗалога</Enum>',
        '<Enum>СостояниеВелосипеда</Enum>',
        '<Document>Резервирование</Document>',
        '<Document>ВыдачаВелосипедов</Document>',
        '<Document>ВозвратВелосипедов</Document>',
        '<AccumulationRegister>ВелосипедыВПрокате</AccumulationRegister>',
        '<AccumulationRegister>Резервы</AccumulationRegister>',
        '<AccumulationRegister>Выручка</AccumulationRegister>',
        '<Report>ВыручкаЗаПериод</Report>',
        '<Report>ВелосипедыВПрокате</Report>',
        '<Report>АналитикаПоКлиентам</Report>',
    ])
    print('generated ->', out)


def build_reports(out):
    # выручка за период по моделям — гистограмма
    q1 = ("ВЫБРАТЬ\n"
          "\tВыручкаОбороты.Модель КАК Модель,\n"
          "\tВыручкаОбороты.Клиент КАК Клиент,\n"
          "\tВыручкаОбороты.СуммаОборот КАК Сумма,\n"
          "\tВыручкаОбороты.ЧасыОборот КАК Часы\n"
          "ИЗ\n"
          "\tРегистрНакопления.Выручка.Обороты КАК ВыручкаОбороты")
    f1 = [dcs.field('Модель', 'Модель'), dcs.field('Клиент', 'Клиент'),
          dcs.field('Сумма', 'Сумма'), dcs.field('Часы', 'Часы')]
    t1 = [('Сумма', 'Сумма(Сумма)'), ('Часы', 'Сумма(Часы)')]
    q_chart = ("ВЫБРАТЬ\n"
               "\tВыручкаОбороты.Модель КАК Точка,\n"
               "\tВыручкаОбороты.СуммаОборот КАК Значение\n"
               "ИЗ\n"
               "\tРегистрНакопления.Выручка.Обороты(, , , ) КАК ВыручкаОбороты\n"
               "УПОРЯДОЧИТЬ ПО\n"
               "\tЗначение УБЫВ")
    report_chart(out, 'ВыручкаЗаПериод', 'Выручка за период', q_chart, "Выручка")

    # кто сейчас катается
    q2 = ("ВЫБРАТЬ\n"
          "\tОстатки.Велосипед КАК Велосипед,\n"
          "\tОстатки.Клиент КАК Клиент,\n"
          "\tОстатки.КоличествоОстаток КАК Количество\n"
          "ИЗ\n"
          "\tРегистрНакопления.ВелосипедыВПрокате.Остатки КАК Остатки")
    f2 = [dcs.field('Велосипед', 'Велосипед'), dcs.field('Клиент', 'Клиент'),
          dcs.field('Количество', 'Количество')]
    v2 = dcs.variant_details('Основной', 'Основной', ['Велосипед', 'Клиент', 'Количество'])
    report(out, 'ВелосипедыВПрокате', 'Велосипеды в прокате',
           dcs.schema(q2, f2, totals=[('Количество', 'Сумма(Количество)')], variants=[v2]))

    # аналитика по клиентам: постояльцы гостиниц отдельно
    q3 = ("ВЫБРАТЬ\n"
          "\tВыручкаОбороты.Клиент КАК Клиент,\n"
          "\tВыручкаОбороты.Клиент.ПостоялецГостиницы КАК ПостоялецГостиницы,\n"
          "\tВыручкаОбороты.Клиент.Гостиница КАК Гостиница,\n"
          "\tВыручкаОбороты.Модель КАК Модель,\n"
          "\tВыручкаОбороты.СуммаОборот КАК Сумма\n"
          "ИЗ\n"
          "\tРегистрНакопления.Выручка.Обороты КАК ВыручкаОбороты")
    f3 = [dcs.field('Клиент', 'Клиент'), dcs.field('ПостоялецГостиницы', 'ПостоялецГостиницы'),
          dcs.field('Гостиница', 'Гостиница'), dcs.field('Модель', 'Модель'),
          dcs.field('Сумма', 'Сумма')]
    v3 = dcs.variant_details('Основной', 'Основной',
                             ['Клиент', 'Гостиница', 'Модель', 'Сумма'],
                             filters=[('ПостоялецГостиницы', 'Equal', u(), 'Постоялец гостиницы')],
                             order=[('Сумма', 'Desc')],
                             group_fields=['ПостоялецГостиницы'])
    report(out, 'АналитикаПоКлиентам', 'Аналитика по клиентам',
           dcs.schema(q3, f3, totals=[('Сумма', 'Сумма(Сумма)')], variants=[v3]))


if __name__ == '__main__':
    target = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))), '_build', 'prokat')
    build(target)
