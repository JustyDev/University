def build(out):
    if os.path.isdir(out):
        shutil.rmtree(out)
    os.makedirs(out)

    # --- справочник ---
    catalog(out, 'Товары', 'Товары', 'Товар', 'Товары', descr_len=50)

    # --- регистр накопления ---
    # Задание 10, пункт 1: у измерения «СрокГодности» состав даты — только дата,
    # поэтому в отчётах не появляется 00:00:00.
    accum_register(out, 'ОстаткиТоваров', 'Остатки товаров',
        dims=[
            attribute('Товар', 'Товар', type_ref('Catalog', 'Товары'), tag='Dimension'),
            attribute('СрокГодности', 'Срок годности', type_date('Date'), tag='Dimension'),
        ],
        ress=[
            attribute('Количество', 'Количество', type_number(15, 3), tag='Resource'),
        ])

    # --- документы ---
    postuplenie_ts = tabular_section('Состав', 'Состав', owner='ПоступлениеТоваров', attrs=[
        attribute('Товар', 'Товар', type_ref('Catalog', 'Товары'), fill='ShowError', indent=5),
        attribute('Количество', 'Количество', type_number(15, 3, nonneg=True), fill='ShowError', indent=5),
        attribute('СрокГодности', 'Срок годности', type_date('Date'), fill='ShowError', indent=5),
    ])
    document(out, 'ПоступлениеТоваров', 'Поступление товаров',
             tabsecs=[postuplenie_ts],
             registers=['AccumulationRegister.ОстаткиТоваров'],
             module=MOD_POSTUPLENIE)

    prodazha_ts = tabular_section('Состав', 'Состав', owner='ПродажаТоваров', attrs=[
        attribute('Товар', 'Товар', type_ref('Catalog', 'Товары'), fill='ShowError', indent=5),
        attribute('Количество', 'Количество', type_number(15, 3, nonneg=True), fill='ShowError', indent=5),
    ])
    document(out, 'ПродажаТоваров', 'Продажа товаров',
             tabsecs=[prodazha_ts],
             registers=['AccumulationRegister.ОстаткиТоваров'],
             module=MOD_PRODAZHA)

    # --- отчёт на СКД (задание 10, пункт 2) ---
    q = ("ВЫБРАТЬ\n"
         "\tОстаткиТоваровОстатки.Товар КАК Товар,\n"
         "\tОстаткиТоваровОстатки.СрокГодности КАК СрокГодности,\n"
         "\tОстаткиТоваровОстатки.КоличествоОстаток КАК КоличествоОстаток\n"
         "ИЗ\n"
         "\tРегистрНакопления.ОстаткиТоваров.Остатки КАК ОстаткиТоваровОстатки")
    fields = [
        dcs.field('Товар', 'Товар'),
        dcs.field('СрокГодности', 'СрокГодности'),
        dcs.field('КоличествоОстаток', 'КоличествоОстаток'),
    ]
    variant = dcs.variant_details(
        'Основной', 'Основной',
        ['Товар', 'СрокГодности', 'КоличествоОстаток'],
        filters=[('Товар', 'Equal', u(), 'Товар')],
        order=[('Товар', 'Asc'), ('СрокГодности', 'Asc')])
    schema = dcs.schema(q, fields,
                        totals=[('КоличествоОстаток', 'Сумма(КоличествоОстаток)')],
                        variants=[variant])
    report(out, 'ОстаткиТоваровСКД', 'Остатки товаров (СКД)', schema)

    # --- «старый» отчёт: табличный документ, заполняемый кодом ---
    report_plain(out, 'ОстаткиТоваровТаблица', 'Остатки товаров (таблица)')

    # --- подсистемы ---
    subsystem(out, 'Учет', 'Учёт', [
        'Catalog.Товары', 'Document.ПоступлениеТоваров', 'Document.ПродажаТоваров',
        'AccumulationRegister.ОстаткиТоваров'])
    subsystem(out, 'Отчеты', 'Отчёты', [
        'Report.ОстаткиТоваровСКД', 'Report.ОстаткиТоваровТаблица'])

    configuration(out, 'КонтрольГодности', 'Контроль годности', [
        '<Subsystem>Учет</Subsystem>',
        '<Subsystem>Отчеты</Subsystem>',
        '<Catalog>Товары</Catalog>',
        '<Document>ПоступлениеТоваров</Document>',
        '<Document>ПродажаТоваров</Document>',
        '<AccumulationRegister>ОстаткиТоваров</AccumulationRegister>',
        '<Report>ОстаткиТоваровСКД</Report>',
        '<Report>ОстаткиТоваровТаблица</Report>',
    ])
    print('generated ->', out)


def report_plain(out, name, synonym):
    """Отчёт без схемы компоновки: форма с табличным документом и кнопкой «Сформировать»."""
    body = [
        '\t<Report uuid="%s">' % u(),
        '\t\t<InternalInfo>',
        gentypes('Report', name, ['Object', 'Manager'], 3),
        '\t\t</InternalInfo>',
        '\t\t<Properties>',
        '\t\t\t<Name>%s</Name>' % name,
        syn(synonym),
        '\t\t\t<Comment/>',
        '\t\t\t<UseStandardCommands>true</UseStandardCommands>',
        '\t\t\t<DefaultForm>Report.%s.Form.ФормаОтчета</DefaultForm>' % name,
        '\t\t</Properties>',
        '\t\t<ChildObjects>',
        '\t\t\t<Form>ФормаОтчета</Form>',
        '\t\t</ChildObjects>',
        '\t</Report>',
    ]
    write(os.path.join(out, 'Reports', name + '.xml'), '\n'.join(body))

    ids = forms.Ids(1)
    items = [
        forms.button('Сформировать', 'Сформировать', ids, title='Сформировать'),
        '\t\t<SpreadsheetDocumentField name="РезультатОтчета" id="%d">\n'
        '\t\t\t<DataPath>РезультатОтчета</DataPath>\n'
        '\t\t\t<Height>25</Height>\n'
        '\t\t\t<AutoMaxHeight>false</AutoMaxHeight>\n'
        '\t\t\t<VerticalStretch>true</VerticalStretch>\n'
        '\t\t\t<HorizontalStretch>true</HorizontalStretch>\n'
        '\t\t</SpreadsheetDocumentField>' % ids.next(),
    ]
    attrs = [
        forms.attribute('Объект', '<v8:Type>cfg:ReportObject.%s</v8:Type>' % name, main=True, aid=1),
        forms.attribute('РезультатОтчета', '<v8:Type>v8ui:SpreadsheetDocument</v8:Type>',
                        title='Результат', aid=85),
    ]
    cmds = [forms.command('Сформировать', 'Сформировать', 'Сформировать', ids)]
    xml = forms.form_xml(items, attrs, cmds)
    forms.write_form(os.path.join(out, 'Reports', name), 'ФормаОтчета', 'Форма отчёта',
                     xml, module=REPORT_FORM_MODULE)


if __name__ == '__main__':
    target = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))), '_build', 'godnost')
    build(target)
